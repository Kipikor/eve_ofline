    /// <summary>
    /// Generated static identities for every mineable high-security system in
    /// The Forge. System/belt IDs, English names, celestial/orbit indices and
    /// raw security values come from CCP's official SDE build 3466501
    /// (2026-08-13). Resource mixes, NPC pressure and generated rock layouts
    /// remain explicit gameplay approximations.
    /// </summary>
    internal static class HighSecBeltCatalog
    {
        internal const int SourceSystemCount = 70;
        internal const int SourceBeltCount = 659;

        static readonly string[] HighTierOres = { "veldspar", "scordite", "pyroxeres" };
        static readonly string[] LowerTierOres = { "veldspar", "scordite", "pyroxeres", "plagioclase" };
        static readonly int[] RomanValues = { 10, 9, 5, 4, 1 };
        static readonly string[] RomanSymbols = { "X", "IX", "V", "IV", "I" };

        internal static int AddMissingTheForgeBelts(List<LocationDefinition> locations)
        {
            if (locations == null) throw new ArgumentNullException(nameof(locations));
            if (Systems.Length != SourceSystemCount)
                throw new InvalidOperationException($"The Forge SDE catalog expected {SourceSystemCount} systems, found {Systems.Length}.");

            var existingBeltIds = new HashSet<long>();
            var existingLocationIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var location in locations)
            {
                if (location == null) continue;
                existingLocationIds.Add(location.Id);
                if (location.BeltId > 0) existingBeltIds.Add(location.BeltId);
            }

            var sourceBeltIds = new HashSet<long>();
            var sourceBeltCount = 0;
            var added = 0;
            foreach (var system in Systems)
            {
                var profile = ProfileFor(system.Security);
                foreach (var encodedBelt in system.Belts.Split(','))
                {
                    ParseBelt(encodedBelt, out var beltId, out var celestialIndex, out var orbitIndex);
                    sourceBeltCount++;
                    if (!sourceBeltIds.Add(beltId))
                        throw new InvalidOperationException($"Duplicate SDE asteroid belt ID {beltId}.");
                    if (existingBeltIds.Contains(beltId)) continue;

                    var locationId = $"sde-belt-{beltId}";
                    if (!existingLocationIds.Add(locationId))
                        throw new InvalidOperationException($"Duplicate mining location ID {locationId}.");
                    existingBeltIds.Add(beltId);
                    locations.Add(new LocationDefinition(
                        locationId,
                        system.Name,
                        system.SystemId,
                        $"{system.Name} {ToRoman(celestialIndex)} - Asteroid Belt {orbitIndex}",
                        beltId,
                        system.Security,
                        profile.OreIds,
                        profile.Threat,
                        profile.SpawnMinSeconds,
                        profile.SpawnMaxSeconds,
                        profile.MaxNpcCount));
                    added++;
                }
            }

            if (sourceBeltCount != SourceBeltCount)
                throw new InvalidOperationException($"The Forge SDE catalog expected {SourceBeltCount} belts, found {sourceBeltCount}.");
            return added;
        }

        static ThreatProfile ProfileFor(float security)
        {
            var displayedTier = (int)Math.Round(security * 10d, MidpointRounding.AwayFromZero);
            if (displayedTier >= 9) return new ThreatProfile(HighTierOres, 0f, 9999f, 9999f, 0);
            if (displayedTier == 8) return new ThreatProfile(HighTierOres, .14f, 210f, 420f, 2);
            if (displayedTier == 7) return new ThreatProfile(LowerTierOres, .34f, 145f, 290f, 3);
            if (displayedTier == 6) return new ThreatProfile(LowerTierOres, .41f, 130f, 260f, 3);
            return new ThreatProfile(LowerTierOres, .48f, 120f, 240f, 3);
        }

        static void ParseBelt(string encoded, out long beltId, out int celestialIndex, out int orbitIndex)
        {
            var parts = encoded.Split(':');
            if (parts.Length != 3 || !long.TryParse(parts[0], out beltId) ||
                !int.TryParse(parts[1], out celestialIndex) || !int.TryParse(parts[2], out orbitIndex) ||
                beltId <= 0 || celestialIndex <= 0 || orbitIndex <= 0)
                throw new InvalidOperationException($"Malformed SDE asteroid belt spec '{encoded}'.");
        }

        static string ToRoman(int value)
        {
            if (value <= 0) throw new ArgumentOutOfRangeException(nameof(value));
            var result = string.Empty;
            for (var i = 0; i < RomanValues.Length; i++)
                while (value >= RomanValues[i])
                {
                    result += RomanSymbols[i];
                    value -= RomanValues[i];
                }
            return result;
        }

        readonly struct ThreatProfile
        {
            public readonly string[] OreIds;
            public readonly float Threat;
            public readonly float SpawnMinSeconds;
            public readonly float SpawnMaxSeconds;
            public readonly int MaxNpcCount;

            public ThreatProfile(string[] oreIds, float threat, float spawnMinSeconds, float spawnMaxSeconds, int maxNpcCount)
            {
                OreIds = oreIds;
                Threat = threat;
                SpawnMinSeconds = spawnMinSeconds;
                SpawnMaxSeconds = spawnMaxSeconds;
                MaxNpcCount = maxNpcCount;
            }
        }

